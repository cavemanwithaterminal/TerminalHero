#  Das Moleratgebiet ist der zentrale Bau der Steppe. Hier leben
#  zwei Molerats (Gegner/Molerats.sh). Werden sie gelöscht, kommt
#  alle 24 Ingame-Stunden ein Molerat nach, bis das Maximum von
#  zwei wieder erreicht ist.
#
#  Im Gebiet liegen sechs Untergebiete:
#    Moleratgebiet1.1 -> Moleratgebiet1.2
#    Moleratgebiet2.1 -> Moleratgebiet2.2
#    Moleratgebiet3.1 -> Moleratgebiet3.2
#  Jedes dieser Untergebiete hält drei Molerats und hat einen
#  eigenen, unabhängigen 24-Stunden-Respawn.
#
#  Der Ordner gehört zum statischen Grundgerüst (kern/fs.sh);
#  die Molerats setzt Gegner/Molerats.sh dynamisch.
