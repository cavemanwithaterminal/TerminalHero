#  TerminalHero - Ort: .../Höhlentunnel3/GroßeHöhlenkammer
# ------------------------------------------------------------
#  Die Große Höhlenkammer bildet den Abschluss der Tunnelkette
#  im Canyon. Von hier zweigen drei Tunnelketten ab:
#
#    Westtunnel1 -> Westtunnel2 (+ NebenkammerWest) -> Westtunnel3
#                   -> KammerEndeWest
#    Osttunnel1  -> Osttunnel2  (+ NebenkammerOst)  -> Osttunnel3
#                   -> KammerEndeOst
#    Nordtunnel1 -> Nordtunnel2 (+ NebenkammerNord) -> Nordtunnel3
#                   -> GroßerHöhleneingang
#
#  In der Kammer leben fünf Molerats (Gegner/Molerats.sh). Getötete
#  Tiere kommen alle 24 Ingame-Stunden einzeln nach, bis das Maximum
#  von fünf wieder erreicht ist. Zusätzlich halten hier bis zu zwei
#  MoleratKrieger; sie kommen alle 48 Ingame-Stunden einzeln nach.
#
#  Der Ordner gehört zum statischen Grundgerüst (kern/fs.sh); die
#  Gegner setzt Gegner/Molerats.sh dynamisch.
# ============================================================
