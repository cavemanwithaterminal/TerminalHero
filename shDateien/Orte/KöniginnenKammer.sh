#  Die KöniginnenKammer liegt am Ende des Breiten Tunnels. Ein
#  gewaltiger, runder Raum, dessen Wände von alten Grabungsspuren
#  bedeckt sind. In der Mitte liegt ein Nest aus Fellen, Knochen
#  und zerbrochenem Gestein.
#
#  Hier lebt die MoleratKönigin (Gegner/MoleratKoenigin.sh) –
#  ein riesiges, massiges Schwein. Um sie herum halten bis zu drei
#  MoleratKrieger Wache; sie kommen alle zwei Ingame-Tage einzeln
#  nach. Die Königin selbst kehrt nicht zurück.
#
#  Am Rand des Nests liegt das »SchweinePriester's Tagebuch«
#  (Items/Quest/SchweinePriesterTagebuch.sh). Es ist ein Fundort
#  und wird mit »grep SchweinePriesterTagebuch« aufgenommen.
#
#  Der Ordner gehört zum statischen Grundgerüst (kern/fs.sh); die
#  Gegner setzt Gegner/MoleratKoenigin.sh dynamisch.
